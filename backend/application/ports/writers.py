from datetime import date, datetime
from typing import Protocol

from ...domain.models import QuoteSeries, RankingBoard
from ...domain.rankings import RankingItem, RankingProgress


class QuoteWriter(Protocol):
    def append(self, secid: str, time: datetime, price: float) -> QuoteSeries: ...


class RankingWriter(Protocol):
    def claim(self, trade_date: date, owner: str, now: datetime, lease_seconds: int) -> bool: ...
    def heartbeat(self, owner: str, now: datetime, lease_seconds: int) -> bool: ...
    def record(self, trade_date: date, item: RankingItem, progress: RankingProgress, owner: str, now: datetime, lease_seconds: int) -> None: ...
    def set_progress(self, progress: RankingProgress, owner: str) -> None: ...
    def publish(self, board: RankingBoard, owner: str, now: datetime) -> None: ...
    def fail(self, owner: str, message: str, now: datetime) -> None: ...
    def release(self, owner: str, now: datetime) -> None: ...
    def note_error(self, message: str, now: datetime) -> None: ...
