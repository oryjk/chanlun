from datetime import datetime
from typing import Protocol

from ...domain.app_auth import (
    AppIdentity,
    AppleIdentity,
    EmailVerificationChallenge,
    LoginChallenge,
    Revocation,
)


class AppleGateway(Protocol):
    def verify_and_exchange(self, token: str, code: str, nonce: str) -> AppleIdentity: ...
    def revoke(self, token: str) -> None: ...


class EmailCodeGateway(Protocol):
    def send_verification_code(self, email: str, code: str, expires_minutes: int) -> None: ...


class AppAuthReader(Protocol):
    def session(self, token: str, now: datetime) -> AppIdentity | None: ...
    def pending_revocations(self) -> tuple[Revocation, ...]: ...
    def find_email_credentials(self, email_key: str) -> tuple[AppIdentity, str] | None: ...


class AppAuthWriter(Protocol):
    def add_challenge(self, challenge: LoginChallenge) -> None: ...
    def consume_challenge(self, challenge_id: str, now: datetime) -> LoginChallenge: ...
    def login(self, identity: AppleIdentity, nickname: str | None, token: str,
              expires_at: datetime, challenge: LoginChallenge, now: datetime) -> AppIdentity: ...
    def save_email_code(self, challenge: EmailVerificationChallenge, cooldown_seconds: int) -> None: ...
    def register_email(self, email_key: str, code_digest: str, password_hash: str, nickname: str,
                       token: str, expires_at: datetime, now: datetime) -> AppIdentity: ...
    def create_session(self, user_id: str, token: str, expires_at: datetime, now: datetime) -> None: ...
    def logout(self, token: str) -> None: ...
    def delete_account(self, token: str, now: datetime) -> None: ...
    def finish_revocation(self, job_id: str) -> None: ...
    def process_event(self, event_id: str, subject: str, kind: str, now: datetime, event_time: float) -> bool: ...
